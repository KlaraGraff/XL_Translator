"""Email the users whose feedback a release resolves.

Runs after ``release.yml`` publishes a version (and by hand for a dry run).
Works on the private feedback repository the relay files issues into:

* an issue waiting for a notice carries the label ``待通知`` and a comment
  that starts with ``<!-- xl-notify version=X.Y.Z -->``, then a line
  ``主题：…`` (or ``Subject: …``), a blank line and the email body, written
  in the user's interface language;
* once the published version is at least X.Y.Z, the body goes to the address
  in the issue's ``**联系方式**`` line, from the app's own mailbox over SMTP;
* the issue then gets a short comment (without the address), the label
  ``已通知`` instead of ``待通知``, and is closed as completed.

Issues without a usable address are labelled ``无邮箱`` and closed.

``--prerelease --issue N`` sends a pre-release (a build only some users try
first) to the listed issues only, once that version is published as a GitHub
Pre-release. Installed apps never offer a pre-release, so the mail links its
release page instead of telling the user to update in the app; the issue is
then closed as usual and gets no second mail when the version goes formal. Logs of
this public repository never show an address or the email text.

Environment: FEEDBACK_GITHUB_TOKEN, FEEDBACK_REPO (default
KlaraGraff/XL_Translator-feedback), FEEDBACK_SMTP_USER,
FEEDBACK_SMTP_PASSWORD, FEEDBACK_SMTP_HOST (default smtp.gmail.com),
FEEDBACK_SMTP_PORT (default 465).
"""

from __future__ import annotations

import argparse
import html
import json
import os
import re
import smtplib
import sys
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from email.message import EmailMessage
from email.utils import formataddr, make_msgid
from typing import Any

PENDING_LABEL = "待通知"
DONE_LABEL = "已通知"
NO_EMAIL_LABEL = "无邮箱"
SENDER_NAME = "Translator"
_MARKER_RE = re.compile(r"^\s*<!--\s*xl-notify\s+version=v?(\d+\.\d+\.\d+)\s*-->\s*$")
_SUBJECT_RE = re.compile(r"^\s*(?:主题|Subject|Objet)\s*[:：]\s*(.+?)\s*$", re.IGNORECASE)
_CONTACT_RE = re.compile(r"^\*\*联系方式\*\*：`([^`]*)`", re.MULTILINE)
_REFERENCE_RE = re.compile(r"^\*\*编号\*\*：\s*([A-Za-z0-9-]+)", re.MULTILINE)
_LANGUAGE_RE = re.compile(r"界面语言\s+([A-Za-z-]+)")
_EMAIL_RE = re.compile(r"^[^\s@]+@[^\s@]+\.[^\s@]+$")
# Claude 经 GitHub 工具发的评论末尾会自动带上这行署名，不能跟着进用户的邮件。
_FOOTER_RE = re.compile(r"\n\s*-{3,}\s*\n\s*_?Generated by \[Claude Code\]\([^)]*\)_?\s*$")
# 邮件末尾统一由脚本署名；通知里自己写的署名行先去掉，免得出现两遍。
_SIGNATURE_RE = re.compile(r"\n\s*(?:[—–-]+\s*)?(?:XL\s+)?Translator\s*$", re.IGNORECASE)
SIGNATURE = "—— Translator"
RELEASES_URL = "https://github.com/KlaraGraff/XL_Translator/releases/latest"
# 每封通知末尾统一说明怎么装上新版本，按用户的界面语言；先写应用内更新（会校验签名），
# 发布页链接兜底。链到发布页而不是安装包：用户的系统不一定，发布页上还有校验文件和更新说明。
UPDATE_HINTS = {
    "zh": f"更新方法：在应用的「设置 → 更新与关于」中点击更新即可，原有设置和数据都会保留。如需手动安装，请在发布页下载最新版本：{RELEASES_URL}",
    "en": f"To update, open Settings → Updates & about in the app and click Update; your settings and data are kept. To install manually, download the latest version from the release page: {RELEASES_URL}",
    "fr": f"Pour mettre à jour, ouvrez Paramètres → Mises à jour dans l’application et cliquez sur Mettre à jour\u00a0; vos paramètres et vos données sont conservés. Pour une installation manuelle, téléchargez la dernière version sur la page de publication\u00a0: {RELEASES_URL}",
}
# 预发布在应用内看不到，只能从它自己的发布页下载安装包。
PRERELEASE_HINTS = {
    "zh": "这是预发布的测试版，应用内的更新检查暂时不会提示它。请在下面的发布页下载与您系统对应的安装包，直接安装即可，原有设置和数据都会保留：{url}",
    "en": "This is a pre-release test build, so the in-app update check does not offer it yet. Download the installer for your system from the release page below and install it directly; your settings and data are kept: {url}",
    "fr": "Il s’agit d’une version de test préliminaire : la vérification des mises à jour dans l’application ne la propose pas encore. Téléchargez le programme d’installation correspondant à votre système sur la page ci-dessous et installez-le directement ; vos paramètres et vos données sont conservés : {url}",
}
_URL_RE = re.compile(r"https://[^\s<>\"']+")


@dataclass
class Notice:
    version: tuple[int, int, int]
    subject: str
    body: str


def parse_version(text: str) -> tuple[int, int, int]:
    match = re.fullmatch(r"v?(\d+)\.(\d+)\.(\d+)", text.strip())
    if not match:
        raise ValueError(f"版本号格式应为 X.Y.Z：{text}")
    return int(match[1]), int(match[2]), int(match[3])


def parse_notice(comment: str) -> Notice | None:
    lines = comment.replace("\r\n", "\n").split("\n")
    if not lines:
        return None
    marker = _MARKER_RE.match(lines[0])
    if not marker or len(lines) < 2:
        return None
    subject = _SUBJECT_RE.match(lines[1])
    body = _SIGNATURE_RE.sub("", _FOOTER_RE.sub("", "\n".join(lines[2:])).strip()).strip()
    if not subject or not body:
        return None
    return Notice(parse_version(marker[1]), subject[1], body)


def feedback_reference(issue_body: str) -> str:
    match = _REFERENCE_RE.search(issue_body or "")
    return match[1] if match else ""


def with_reference(notice: Notice, reference: str) -> Notice:
    """Add the feedback number after the subject so mail can be searched by it."""
    if not reference or reference in notice.subject:
        return notice
    # 给人看的标题在前，编号放在后面；中文主题用全角括号。
    suffix = f"（{reference}）" if re.search(r"[\u4e00-\u9fff]", notice.subject) else f" ({reference})"
    return Notice(notice.version, f"{notice.subject}{suffix}", notice.body)


def ui_language(issue_body: str) -> str:
    match = _LANGUAGE_RE.search(issue_body or "")
    code = match[1].lower().split("-")[0] if match else ""
    return code if code in UPDATE_HINTS else "zh"


def release_page_url(version: tuple[int, int, int]) -> str:
    return f"https://github.com/KlaraGraff/XL_Translator/releases/tag/v{'.'.join(map(str, version))}"


def with_update_hint(notice: Notice, language: str, *, prerelease_url: str = "") -> Notice:
    """Append how to install the new version, unless the notice already links the release page."""
    if prerelease_url:
        if prerelease_url in notice.body:
            return notice
        hint = PRERELEASE_HINTS.get(language, PRERELEASE_HINTS["zh"]).format(url=prerelease_url)
        return Notice(notice.version, notice.subject, f"{notice.body}\n\n{hint}")
    if RELEASES_URL in notice.body:
        return notice
    hint = UPDATE_HINTS.get(language, UPDATE_HINTS["zh"])
    return Notice(notice.version, notice.subject, f"{notice.body}\n\n{hint}")


def contact_email(issue_body: str) -> str:
    match = _CONTACT_RE.search(issue_body or "")
    address = match[1].strip() if match else ""
    return address if _EMAIL_RE.match(address) else ""


def mask(address: str) -> str:
    name, _, domain = address.partition("@")
    return f"{name[:1]}***@{domain}" if domain else "***"


def build_message(sender: str, to: str, notice: Notice) -> EmailMessage:
    message = EmailMessage()
    message["From"] = formataddr((SENDER_NAME, sender))
    message["To"] = to
    message["Subject"] = notice.subject
    message["Message-ID"] = make_msgid(domain=sender.partition("@")[2] or None)
    # 纯文本给不显示 HTML 的客户端；HTML 版按段落排版，落款靠右。
    message.set_content(f"{notice.body}\n\n{SIGNATURE}\n")
    message.add_alternative(_html_body(notice.body), subtype="html")
    return message


def _html_line(line: str) -> str:
    # HTML 版里链接可以点；其余文字照常转义。
    parts: list[str] = []
    last = 0
    for match in _URL_RE.finditer(line):
        url = html.escape(match[0], quote=True)
        parts.append(html.escape(line[last:match.start()]))
        parts.append(f'<a href="{url}" style="color:#2f5bd3">{url}</a>')
        last = match.end()
    parts.append(html.escape(line[last:]))
    return "".join(parts)


def _html_body(body: str) -> str:
    paragraphs = "".join(
        f'<p style="margin:0 0 1em">{"<br>".join(_html_line(line) for line in block.split(chr(10)))}</p>'
        for block in re.split(r"\n\s*\n", body.strip())
    )
    return (
        '<!doctype html><html><body style="font-family:-apple-system,\'Segoe UI\',\'PingFang SC\','
        '\'Microsoft YaHei\',sans-serif;font-size:14px;line-height:1.7;color:#222">'
        f'<div style="max-width:560px">{paragraphs}'
        f'<p style="margin:1.5em 0 0;text-align:right">{html.escape(SIGNATURE)}</p></div></body></html>\n'
    )


class GitHub:
    def __init__(self, token: str, repo: str) -> None:
        self.token = token
        self.repo = repo

    def request(self, method: str, path: str, payload: Any = None) -> Any:
        url = f"https://api.github.com/repos/{self.repo}{path}"
        data = json.dumps(payload).encode() if payload is not None else None
        request = urllib.request.Request(url, data=data, method=method, headers={
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "xl-translator-feedback-notify",
        })
        with urllib.request.urlopen(request, timeout=30) as response:
            raw = response.read()
        return json.loads(raw) if raw else None

    def pending_issues(self) -> list[dict[str, Any]]:
        label = urllib.parse.quote(PENDING_LABEL)
        issues: list[dict[str, Any]] = []
        page = 1
        while True:
            batch = self.request("GET", f"/issues?state=open&labels={label}&per_page=100&page={page}")
            issues.extend(item for item in batch if "pull_request" not in item)
            if len(batch) < 100:
                return issues
            page += 1

    def comments(self, number: int) -> list[dict[str, Any]]:
        return self.request("GET", f"/issues/{number}/comments?per_page=100")

    def finish(self, number: int, label: str, note: str) -> None:
        self.request("POST", f"/issues/{number}/comments", {"body": note})
        labels = [item["name"] for item in self.request("GET", f"/issues/{number}/labels")]
        labels = [name for name in labels if name != PENDING_LABEL] + [label]
        self.request("PUT", f"/issues/{number}/labels", {"labels": labels})
        self.request("PATCH", f"/issues/{number}", {"state": "closed", "state_reason": "completed"})


def latest_notice(comments: list[dict[str, Any]]) -> Notice | None:
    for comment in reversed(comments):
        notice = parse_notice(str(comment.get("body") or ""))
        if notice:
            return notice
    return None


def run(
    github: GitHub,
    released: tuple[int, int, int],
    *,
    send: Any,
    dry_run: bool,
    only: set[int] | None = None,
    prerelease: bool = False,
) -> int:
    """Send every due notice (only to ``only`` when given); return how many failed."""
    version_text = ".".join(map(str, released))
    prerelease_url = release_page_url(released) if prerelease else ""
    done_note = f"v{version_text} 已发布为预发布，已发邮件请用户试用" if prerelease else f"v{version_text} 已发布，已发邮件通知用户"
    failures = 0
    for issue in github.pending_issues():
        number = int(issue["number"])
        if only is not None and number not in only:
            continue
        notice = latest_notice(github.comments(number))
        if notice is None:
            print(f"#{number}：有「{PENDING_LABEL}」标签但还没写通知，跳过。")
            continue
        if notice.version > released:
            print(f"#{number}：通知属于 {'.'.join(map(str, notice.version))}，本次 {version_text} 不发。")
            continue
        address = contact_email(str(issue.get("body") or ""))
        if not address:
            print(f"#{number}：用户没留可用的邮箱，标为「{NO_EMAIL_LABEL}」并关闭。")
            if not dry_run:
                github.finish(number, NO_EMAIL_LABEL, f"v{version_text} 已发布。用户没有留下可用的邮箱，未发送通知。")
            continue
        if dry_run:
            print(f"#{number}：将发给 {mask(address)}（试运行，未发送）。")
            continue
        try:
            issue_body = str(issue.get("body") or "")
            notice = with_update_hint(
                with_reference(notice, feedback_reference(issue_body)), ui_language(issue_body), prerelease_url=prerelease_url
            )
            send(address, notice)
        except (smtplib.SMTPException, OSError) as exc:
            failures += 1
            print(f"::error::#{number}：发给 {mask(address)} 失败（{type(exc).__name__}），保留「{PENDING_LABEL}」，下次发布再发。")
            continue
        github.finish(number, DONE_LABEL, f"{done_note}（{mask(address)}）。")
        print(f"#{number}：已发给 {mask(address)}。")
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", required=True, help="刚发布的版本号 X.Y.Z")
    parser.add_argument("--dry-run", action="store_true", help="只列出将发送的通知，不发邮件、不改 issue")
    parser.add_argument("--issue", type=int, action="append", help="只发这几个反馈 issue（可重复）")
    parser.add_argument("--prerelease", action="store_true", help="这一版是预发布：必须配合 --issue，邮件链到它的发布页")
    args = parser.parse_args(argv)
    released = parse_version(args.version)
    if args.prerelease:
        if not args.issue:
            parser.error("--prerelease 只发给指定的用户，需要 --issue")
        problem = prerelease_problem(released)
        if problem:
            print(f"::error::{problem}")
            return 1

    token = os.environ.get("FEEDBACK_GITHUB_TOKEN", "")
    if not token:
        print("::warning::没有 FEEDBACK_GITHUB_TOKEN，跳过反馈通知。")
        return 0
    github = GitHub(token, os.environ.get("FEEDBACK_REPO") or "KlaraGraff/XL_Translator-feedback")
    user = os.environ.get("FEEDBACK_SMTP_USER", "")
    password = os.environ.get("FEEDBACK_SMTP_PASSWORD", "")
    dry_run = args.dry_run or not (user and password)
    if dry_run and not args.dry_run:
        print("::warning::还没配置发信邮箱（FEEDBACK_SMTP_USER / FEEDBACK_SMTP_PASSWORD），只试运行。")

    host = os.environ.get("FEEDBACK_SMTP_HOST") or "smtp.gmail.com"
    port = int(os.environ.get("FEEDBACK_SMTP_PORT") or 465)

    def send(address: str, notice: Notice) -> None:
        with smtplib.SMTP_SSL(host, port, timeout=60) as smtp:
            smtp.login(user, password)
            smtp.send_message(build_message(user, address, notice))

    only = set(args.issue) if args.issue else None
    return 1 if run(github, released, send=send, dry_run=dry_run, only=only, prerelease=args.prerelease) else 0


def prerelease_problem(version: tuple[int, int, int]) -> str:
    """Empty when v{version} is a published Pre-release; otherwise why the mail must not go out."""
    tag = f"v{'.'.join(map(str, version))}"
    request = urllib.request.Request(
        f"https://api.github.com/repos/KlaraGraff/XL_Translator/releases/tags/{tag}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "xl-translator-feedback-notify"},
    )
    token = os.environ.get("GITHUB_TOKEN", "")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            release = json.loads(response.read())
    except urllib.error.HTTPError as exc:
        # 草稿对外查不到，也算还没发布。
        return f"{tag} 还没有发布（{exc.code}），不发邮件。"
    return _release_state_problem(tag, release)


def _release_state_problem(tag: str, release: dict[str, Any]) -> str:
    if release.get("draft"):
        return f"{tag} 还是草稿，不发邮件。"
    if not release.get("prerelease"):
        return f"{tag} 已是正式版，请不带 --prerelease 运行。"
    return ""


if __name__ == "__main__":
    sys.exit(main())
